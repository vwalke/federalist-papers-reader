// scripts/generate-debate-migration.mjs
//
// Writes workers/post/migrations/0004_debate.sql from the generated debate
// content, so the weekly progress re-mapping CASE table is derived — never
// hand-typed — and cannot drift from the merged sequence. Run after
// `pnpm generate:email-content`; a unit test cross-checks the committed SQL
// against the content.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const contentFile = join(root, 'workers/post/content/debate.json');
const outFile = join(root, 'workers/post/migrations/0004_debate.sql');

/** old weekly progress (last paper number sent) -> new (merged items consumed). */
export function progressMapping(sequence) {
  const mapping = new Map();
  for (let paper = 1; paper <= 85; paper++) {
    const position = sequence.indexOf(paper);
    if (position === -1) throw new Error(`paper ${paper} missing from the sequence`);
    mapping.set(paper, position + 1);
  }
  return mapping;
}

export function renderMigration(sequence) {
  const cases = [...progressMapping(sequence)]
    .map(([oldProgress, newProgress]) => `  WHEN ${oldProgress} THEN ${newProgress}`)
    .join('\n');
  return `-- The ratification debate joins the post. GENERATED by
-- scripts/generate-debate-migration.mjs from workers/post/content/debate.json;
-- regenerate rather than editing the CASE table by hand.

-- 1. Deliveries widen to the shared id space: 1-85 Publius, 101-116 Brutus,
--    151-166 Cato. SQLite CHECK constraints are immutable, so rebuild the
--    table, preserving rows, ids, the exactly-once UNIQUE, and the index.
CREATE TABLE deliveries_debate (
  id INTEGER PRIMARY KEY AUTOINCREMENT,
  subscriber_id INTEGER NOT NULL REFERENCES subscribers(id) ON DELETE CASCADE,
  paper_number INTEGER NOT NULL CHECK (
    paper_number BETWEEN 1 AND 85
    OR paper_number BETWEEN 101 AND 116
    OR paper_number BETWEEN 151 AND 166
  ),
  scheduled_for TEXT NOT NULL,                 -- ISO date; UNIQUE below = exactly-once
  status TEXT NOT NULL DEFAULT 'queued'
    CHECK (status IN ('queued', 'sent', 'bounced', 'failed')),
  provider_message_id TEXT,
  created_at TEXT NOT NULL DEFAULT (datetime('now')),
  UNIQUE (subscriber_id, paper_number, scheduled_for)
);

INSERT INTO deliveries_debate (id, subscriber_id, paper_number, scheduled_for, status, provider_message_id, created_at)
  SELECT id, subscriber_id, paper_number, scheduled_for, status, provider_message_id, created_at
  FROM deliveries;

DROP TABLE deliveries;
ALTER TABLE deliveries_debate RENAME TO deliveries;
CREATE INDEX idx_deliveries_status ON deliveries (status, created_at);

-- 2. Weekly subscribers who are mid-course owe one make-up email covering the
--    essays that ran before the point they have reached. Calendar subscribers
--    are untouched.
ALTER TABLE subscribers ADD COLUMN makeup_pending INTEGER NOT NULL DEFAULT 0;

UPDATE subscribers SET makeup_pending = 1
WHERE program = 'weekly' AND progress_index > 0;

-- 3. Weekly progress_index changes meaning: "last paper number sent" becomes
--    "count of merged debate items consumed" (new = merged position of the old
--    paper + 1). Zero stays zero; calendar subscribers never used progress.
UPDATE subscribers SET progress_index = CASE progress_index
${cases}
  ELSE progress_index
END
WHERE program = 'weekly' AND progress_index > 0;
`;
}

function main() {
  const { sequence } = JSON.parse(readFileSync(contentFile, 'utf8'));
  writeFileSync(outFile, renderMigration(sequence));
  console.log(`Wrote ${outFile}`);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) main();
